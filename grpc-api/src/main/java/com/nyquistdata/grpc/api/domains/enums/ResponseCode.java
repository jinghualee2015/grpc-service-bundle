public enum ResponseCode {
    SUCCESS(200, "Response ok"),
    FAIL(500, "Response fail"),
    ;
    int code;
    String desc;

    ResponseCode(int code, String desc) {
        this.code = code;
        this.desc = desc;
    }

    public int getCode() {
        return code;
    }

    public String getDesc() {
        return desc;
    }
}
